/**
 * Builds the form-icon set from Lucide (https://lucide.dev, ISC licence, free
 * for any use): every icon in the lucide-react we ship, minus brand logos.
 *
 *   node scripts/gen-form-icons.mjs <path to an unpacked lucide-static package>
 *
 * lucide-static supplies the search tags (its tags.json); lucide-react supplies
 * the drawings. Writes two files that must be committed together:
 *   frontend/src/lib/formIconSet.ts   the picker's list, with search tags
 *   backend/src/forms/iconKeys.ts     the keys the API accepts
 *
 * Keys are stored in the database, so a key that has shipped is never renamed
 * or dropped. The 39 original keys (LEGACY) keep their short names; every
 * other icon's key is its Lucide name, e.g. "heart-handshake".
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const pkgDir = process.argv[2];
if (!pkgDir) {
  console.error("Usage: node scripts/gen-form-icons.mjs <path to unpacked lucide-static package>");
  process.exit(1);
}
const tags = JSON.parse(readFileSync(join(pkgDir, "tags.json"), "utf8"));
const lucide = createRequire(join(root, "frontend/package.json"))("lucide-react");

/** The keys that existed before the set grew: key → [Lucide icon, label]. Order is the picker's "suggested" order. */
const LEGACY = {
  folder: ["folder", "Folder"], utensils: ["utensils", "Food"], users: ["users", "People"], bus: ["bus", "Transport"],
  wallet: ["wallet", "Money"], shield: ["shield", "Security"], briefcase: ["briefcase", "Work"], monitor: ["monitor", "Computer"],
  home: ["house", "Home"], heart: ["heart", "Care"], calendar: ["calendar", "Calendar"], clipboard: ["clipboard-list", "Clipboard"],
  package: ["package", "Package"], file: ["file", "Document"], basket: ["shopping-basket", "Pantry"], soup: ["soup", "Hot meal"],
  cart: ["shopping-cart", "Groceries"], boxes: ["boxes", "Inventory"], contact: ["contact", "Roster"], camera: ["camera", "Photo"],
  gift: ["gift", "Gift"], inspect: ["search-check", "Inspection"], party: ["party-popper", "Event"], "calendar-plus": ["calendar-plus", "Request"],
  train: ["train-front", "Transit"], ticket: ["ticket", "Ticket"], banknote: ["banknote", "Cash"], "piggy-bank": ["piggy-bank", "Savings"],
  receipt: ["receipt", "Receipt"], lock: ["lock", "Lock"], alert: ["triangle-alert", "Incident"], newspaper: ["newspaper", "Newsletter"],
  "user-plus": ["user-plus", "New person"], "hard-hat": ["hard-hat", "Safety"], message: ["message-square", "Conversation"],
  laptop: ["laptop", "Laptop"], help: ["life-buoy", "Help"], history: ["history", "History"], inbox: ["inbox", "Inbox"],
};

/** Company logos: not something a form card should wear. */
const BRANDS = new Set([
  "chrome", "codepen", "codesandbox", "dribbble", "facebook", "figma", "framer", "github", "gitlab", "instagram", "linkedin",
  "pocket", "slack", "trello", "twitch", "twitter", "youtube", "rss",
]);

const pascal = (kebab) => kebab.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const sentence = (kebab) => {
  const s = kebab.replace(/-/g, " ");
  return s[0].toUpperCase() + s.slice(1);
};

const entries = [];
const seen = new Set(); // Pascal component names already placed, so an icon appears once.
function add(key, lucideName, label) {
  const comp = pascal(lucideName);
  if (seen.has(comp)) return;
  if (!(comp in lucide)) throw new Error(`lucide-react has no ${comp} (for ${key})`);
  if (key.length > 40) throw new Error(`Key too long: ${key}`);
  seen.add(comp);
  const words = new Set([...lucideName.split("-"), ...(tags[lucideName] ?? [])].map((w) => w.toLowerCase()));
  entries.push({ key, comp, label, tags: [...words].join(" ") });
}

for (const [key, [name, label]] of Object.entries(LEGACY)) add(key, name, label);
for (const name of Object.keys(tags).sort()) {
  if (BRANDS.has(name)) continue;
  if (!(pascal(name) in lucide)) continue; // in lucide-static but newer than the lucide-react we ship
  // "clipboard" was already taken by the clipboard-list drawing, so the plain
  // Lucide clipboard gets a key of its own.
  add(name in LEGACY ? `${name}-plain` : name, name, sentence(name));
}
if (new Set(entries.map((e) => e.key)).size !== entries.length) throw new Error("Duplicate icon key");
const legacyKept = Object.keys(LEGACY).every((k) => entries.some((e) => e.key === k));
if (!legacyKept) throw new Error("A legacy key was dropped");

const q = JSON.stringify;
const frontend = `// GENERATED by frontend/scripts/gen-form-icons.mjs. Do not edit by hand.
// Icons are Lucide (https://lucide.dev), ISC licence. ${entries.length} icons.
// About 150 KB gzipped, so nothing imports this file directly: formIcons.ts
// loads it on demand (import("./formIconSet")) when the picker opens or a card
// wears an icon outside the original ${Object.keys(LEGACY).length}.
import {
${entries.map((e) => `  ${e.comp},`).join("\n")}
} from "lucide-react";
import type { FormIconDef } from "./formIcons";

/** The first ${Object.keys(LEGACY).length} are the original keys, in the picker's "suggested" order. */
export const FORM_ICON_LIST: readonly FormIconDef[] = [
${entries.map((e) => `  { key: ${q(e.key)}, label: ${q(e.label)}, tags: ${q(e.tags)}, Icon: ${e.comp} },`).join("\n")}
];
`;

const lines = [];
for (let i = 0; i < entries.length; i += 6) lines.push("  " + entries.slice(i, i + 6).map((e) => q(e.key)).join(", ") + ",");
const backend = `// GENERATED by frontend/scripts/gen-form-icons.mjs. Do not edit by hand.
// The icon keys a form card or category may use: every Lucide icon (${entries.length}) bar brand logos.
export const FORM_ICON_KEYS: [string, ...string[]] = [
${lines.join("\n")}
];

/** The keys from before the set grew, which have short names of their own. */
export const LEGACY_FORM_ICON_KEYS = ${q(Object.keys(LEGACY))};
`;

writeFileSync(join(root, "frontend/src/lib/formIconSet.ts"), frontend);
writeFileSync(join(root, "backend/src/forms/iconKeys.ts"), backend);
console.log(`Wrote ${entries.length} icons.`);
